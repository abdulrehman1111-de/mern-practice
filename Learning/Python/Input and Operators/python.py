# Taking input from the user in python

# built in function: input()

name = input("Enter your name: ")
print("Hello", name, "!")

user_age = int(input("Enter your age: "))
print("You are", user_age, "years old")

user_height = float(input("Enter your height: "))
print("Your height is", user_height, "meters")

# Operators in Python

# Arithematic operator
a = 10
b = 3
# +
print(a, "+", b, "=", a + b)
# -
print(a, "-", b, "=", a - b)
# *
print(a, "*", b, "=", a * b)
# /
print(a, "/", b, "=", a / b)
# %
print(a, "%", b, "=", a % b)
# **
print(a, "**", b, "=", a ** b)

# Comparison operators
x = 10
y = 5

# Greater than
print(x, ">", y, "=", x > y)
# less than
print(x, "<", y, "=", x < y)
# Equal to 
print(x, "==", y, "=", x == y)
# Not Equal to 
print(x, "!=", y, "=", x != y)
# Greater than or Equal to 
print(x, ">=", y, "=", x >= y)
# Less than or Equal to 
print(x, "<=", y, "=", x <= y)











